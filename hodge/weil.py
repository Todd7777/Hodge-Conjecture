"""Weil classes on the CM factors of Fermat Jacobians, and how far Markman's theorems reach on Fermat varieties.

See docs/fermat/04-weil-route.md for the statements and proofs.  Pure Python, exact integers.

Dictionary (docs/fermat/04, section 2).  A curve character of degree d is beta = (a, b, c) with a + b + c = 0 (mod d) and
a, b, c != 0.  H^1 of the Fermat curve C_d is the sum of the eigenlines of the curve characters; the eigenline of beta
has type (1,0) iff <a/d> + <b/d> + <c/d> = 1.  The units t of Z/d act by beta -> t*beta.  For one orbit put

    Stab = {t : t*beta = beta},   Phi = {t : t*beta has type (1,0)},   H = {h : Phi*h = Phi}  (so Stab <= H).

The orbit spans H^1 of an abelian variety A_beta with CM by Q(mu_d)^Stab and CM type Phi; A_beta is isogenous to a power
of one simple abelian variety A' of dimension [G : H]/2 with CM by E' = Q(mu_d)^H (the CM type is induced from E').
A class in H^1 x ... x H^1 of a product of such factors whose eigen-decomposition uses the eigencharacters v_1, ..., v_k
corresponds to the element v_1 + ... + v_k of Aoki's formal module R_d (join; Shioda's inductive structure).

For a CM subfield E of Q(mu_d), N = Gal(Q(mu_d)/E) is a subgroup of G = (Z/d)^x with -1 not in N.  A factor A' carries
E-actions through E (E in E') or through a matrix embedding (copies of A'); the part of H^1 on which E acts through a
fixed embedding is an "E-half unit": the eigencharacters t*beta, t running over one coset of N*H modulo H.  The
E-Weil classes of an abelian variety of Weil type relative to E are the sums of such units that are Hodge
(`e_weil_units`, `weil_generators`).
"""

from __future__ import annotations

from dataclasses import dataclass
from math import gcd
from typing import Dict, FrozenSet, List, Optional, Sequence, Tuple

from . import formal_module as F

Tuple_ = Tuple[int, ...]


# ------------------------------------------------------------------------------------------- group helpers

def units(d: int) -> List[int]:
    return [t for t in range(1, d) if gcd(t, d) == 1]


def scale(t: int, v: Sequence[int], d: int) -> Tuple_:
    """t * v as a sorted multiset of residues mod d."""
    return tuple(sorted((t * x) % d for x in v))


def closure(gens: Sequence[int], d: int) -> FrozenSet[int]:
    """The subgroup of (Z/d)^x generated by gens."""
    S, frontier = {1}, [1]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = x * g % d
            if y not in S:
                S.add(y)
                frontier.append(y)
    return frozenset(S)


def subgroups(d: int) -> List[FrozenSet[int]]:
    """All subgroups of (Z/d)^x generated by at most two elements (all subgroups when the group has rank <= 2, as for
    d = 44, 51, 52), sorted by order."""
    G = units(d)
    found = {closure([a, b], d) for a in G for b in G}
    return sorted(found, key=lambda S: (len(S), sorted(S)))


def cm_subgroups(d: int) -> List[FrozenSet[int]]:
    """Subgroups N with -1 not in N, i.e. N = Gal(Q(mu_d)/E) for a CM subfield E."""
    return [N for N in subgroups(d) if (d - 1) % d not in N]


def imaginary_quadratic(d: int) -> List[FrozenSet[int]]:
    """N = Gal(Q(mu_d)/K) for the imaginary quadratic subfields K of Q(mu_d): the index-2 subgroups without -1.
    Computed through G/G^2 (no rank assumption)."""
    G = units(d)
    coords: Dict[int, int] = {t * t % d: 0 for t in G}
    basis: List[int] = []
    for t in G:
        if t in coords:
            continue
        i = len(basis)
        basis.append(t)
        new = {}
        for s, c in coords.items():
            u = s * t % d
            if u not in coords:
                new[u] = c | (1 << i)
        coords.update(new)
        # close up: multiply again by the new elements until stable
        changed = True
        while changed:
            changed = False
            for s, c in list(coords.items()):
                for s2, c2 in list(coords.items()):
                    u = s * s2 % d
                    if u not in coords:
                        coords[u] = c ^ c2
                        changed = True
    assert len(coords) == len(G)
    r = len(basis)
    out = []
    for mask in range(1, 1 << r):
        N = frozenset(s for s, c in coords.items() if bin(c & mask).count("1") % 2 == 0)
        if (d - 1) % d not in N:
            out.append(N)
    return sorted(out, key=sorted)


# ------------------------------------------------------------------------------------------- simple factors

@dataclass(frozen=True)
class Factor:
    beta: Tuple_                 # orbit representative (a, b, c), sorted
    stab: FrozenSet[int]
    phi: FrozenSet[int]          # t with t*beta of type (1,0)
    h: FrozenSet[int]            # {h : phi*h = phi}
    d: int

    @property
    def simple_dim(self) -> int:
        """dim of the simple factor A' (A_beta ~ A'^[H:Stab])."""
        return (len(units(self.d)) // len(self.h)) // 2

    @property
    def dim(self) -> int:
        """dim A_beta."""
        return (len(units(self.d)) // len(self.stab)) // 2

    def eigencharacters(self) -> List[Tuple_]:
        return sorted({scale(t, self.beta, self.d) for t in units(self.d)})


def simple_factors(d: int) -> List[Factor]:
    """One Factor per orbit of (Z/d)^x on curve characters of degree d."""
    G = units(d)
    seen, out = set(), []
    for a in range(1, d):
        for b in range(a, d):
            c = (-a - b) % d
            if c == 0 or c < b:
                continue
            beta = (a, b, c)
            if beta in seen:
                continue
            seen |= {scale(t, beta, d) for t in G}
            stab = frozenset(t for t in G if scale(t, beta, d) == beta)
            phi = frozenset(t for t in G if sum((t * x) % d for x in beta) == d)
            h = frozenset(x for x in G if frozenset(t * x % d for t in phi) == phi)
            out.append(Factor(beta, stab, phi, h, d))
    return out


# ------------------------------------------------------------------------------------------- E-half units

@dataclass(frozen=True)
class Unit:
    """An E-half unit: the eigencharacters of one simple factor on which E acts through one embedding."""
    factor: Factor
    twist: int                   # coset representative g in G / (N H)
    eig: Tuple[Tuple_, ...]      # the eigencharacters t*beta, one per H-coset in g N H
    copies: int                  # [H : N cap H]: copies of A' on which E acts (cost = copies * simple_dim)

    @property
    def cost(self) -> int:
        return self.copies * self.factor.simple_dim

    def element(self) -> Tuple_:
        return tuple(sorted(x for v in self.eig for x in v))

    def defect(self) -> int:
        """#(0,1) - #(1,0) among the eigencharacters at the base embedding (minus the signature defect)."""
        d = self.factor.d
        return sum(1 if sum(x for x in v) > d else -1 for v in self.eig)


def e_weil_units(d: int, N: FrozenSet[int], factors: Optional[List[Factor]] = None) -> List[Unit]:
    """All E-half units for E = Q(mu_d)^N, over all simple factors and all twists."""
    factors = factors if factors is not None else simple_factors(d)
    G = units(d)
    out = []
    for f in factors:
        NH = closure(list(N) + list(f.h), d)
        copies = len(f.h) // len(N & f.h)
        done = set()
        for g in G:
            if g in done:
                continue
            coset = {g * x % d for x in NH}
            done |= coset
            reps, covered = [], set()
            for t in sorted(coset):
                if t in covered:
                    continue
                reps.append(t)
                covered |= {t * x % d for x in f.h}
            out.append(Unit(f, g, tuple(scale(t, f.beta, d) for t in reps), copies))
    return out


def hodge_rows(d: int, elements: Sequence[Sequence[int]]) -> List[List[int]]:
    """Row s (s in half units) of the Hodge condition: sum_v (2 type_s(v) - 3) over the eigencharacters of each element
    (an element given as a concatenation of curve characters, length divisible by 3).  A combination sum c_u u is
    Hodge iff every row annihilates c (the element then has length 3k and sum_i <s a_i> = 3k/2 for all s)."""
    rows = []
    for s in F.half_units(d) + [1]:
        row = []
        for el in elements:
            tot = sum((s * x) % d for x in el)       # = d * sum over eigencharacters of type_s
            k = len(el) // 3
            row.append(2 * tot // d - 3 * k)
        rows.append(row)
    return rows


def parity(element: Sequence[int], q: int) -> int:
    """The parity invariant of docs/fermat/02 (lambda_44, lambda_51, lambda'_52) mod 2; for other q with
    [B_q : D_q + S_q] = 2, the functional of `parity_functional`."""
    if q in F.LAMBDA:
        return sum(F.LAMBDA[q].get(a % q, 0) for a in element) % 2
    phi = parity_functional(q)
    return bin(_mask(F.fold(element, q)) & phi).count("1") % 2


def _mask(vec: Sequence[int]) -> int:
    m = 0
    for i, c in enumerate(vec):
        if c % 2:
            m |= 1 << i
    return m


def _gf2_solve(rows: Sequence[int], target: int) -> Optional[int]:
    """phi (bitmask) with <phi, r> = 0 for every r in rows and <phi, target> = 1, or None."""
    piv: Dict[int, Tuple[int, int]] = {}
    for v, b in [(r, 0) for r in rows] + [(target, 1)]:
        for c, (pv, pb) in piv.items():
            if v >> c & 1:
                v ^= pv
                b ^= pb
        if v == 0:
            if b:
                return None
            continue
        c = v.bit_length() - 1
        for c2 in list(piv):
            pv, pb = piv[c2]
            if pv >> c & 1:
                piv[c2] = (pv ^ v, pb ^ b)
        piv[c] = (v, b)
    phi = 0
    for c, (v, b) in piv.items():
        if b:
            phi |= 1 << c
    return phi


_PHI_CACHE: Dict[int, int] = {}


def parity_functional(q: int) -> int:
    """A mod-2 functional on the folded coordinates (R_q modulo D_q) that kills S_q and is 1 on some element of
    B_q outside D_q + S_q.  When [B_q : D_q + S_q] = 2 it is 1 exactly on the class of xi_q."""
    if q not in _PHI_CACHE:
        B = F.hodge_lattice_folded(q)
        S = F.span_folded(F.standard_tuples(q), q)
        rows = [_mask(F.fold(s, q)) for s in F.standard_tuples(q)]
        phi = None
        for row in B.basis():
            if not S.contains(row):
                phi = _gf2_solve(rows, _mask(row))
                if phi is not None:
                    break
        if phi is None:
            raise ValueError(f"B_{q} = D_{q} + S_{q}")
        _PHI_CACHE[q] = phi
    return _PHI_CACHE[q]


def odd_e_weil_exists(q: int, N: FrozenSet[int], factors: Optional[List[Factor]] = None) -> bool:
    """Is there an integer combination of E-half units (E = Q(mu_q)^N) that is Hodge and has odd parity?

    Exact: a Z-basis of the lattice {c : sum c_u u is Hodge} is computed and the parity evaluated on it.  A negative
    coefficient stands for the complex-conjugate unit, which is again a unit, so a False answer excludes every E-Weil
    element of every abelian variety of Weil type relative to E built from J(C_q).  A True answer only says the lattice
    contains one; explicit non-negative realizations are in REALIZATIONS."""
    us = e_weil_units(q, N, factors)
    els = [u.element() for u in us]
    rows = hodge_rows(q, els)
    par = [parity(e, q) for e in els]
    for c in F.integer_kernel(rows, len(us)).basis():
        if sum(ci * pi for ci, pi in zip(c, par)) % 2:
            return True
    return False


# ------------------------------------------------------------------------------------------- Weil generators

def kernel_basis(m: Sequence[int]) -> List[List[int]]:
    """A Z-basis of {c : sum c_i m_i = 0}, by unimodular column operations."""
    n = len(m)
    vals = list(m)
    basis = [[1 if i == j else 0 for j in range(n)] for i in range(n)]
    while True:
        nz = [i for i in range(n) if vals[i]]
        if len(nz) <= 1:
            break
        i = min(nz, key=lambda k: abs(vals[k]))
        for k in nz:
            if k != i:
                qt = vals[k] // vals[i]
                vals[k] -= qt * vals[i]
                basis[k] = [x - qt * y for x, y in zip(basis[k], basis[i])]
    return [basis[k] for k in range(n) if vals[k] == 0]


def combine(units_: Sequence[Unit], c: Sequence[int], d: int) -> Dict[int, int]:
    """sum c_u u as residue counts; negative coefficients use the complex-conjugate unit (-u = conj(u) mod D_d)."""
    counts: Dict[int, int] = {}
    for cu, u in zip(c, units_):
        if not cu:
            continue
        for x in u.element():
            y = x if cu > 0 else (-x) % d
            counts[y] = counts.get(y, 0) + abs(cu)
    return counts


def weil_generators(d: int, N: FrozenSet[int], factors: Optional[List[Factor]] = None) -> List[Dict[int, int]]:
    """Generators (mod D_d) of the Weil elements relative to the imaginary quadratic field K = Q(mu_d)^N: sums of K-half
    units (one per simple factor whose CM field contains K; the twist only conjugates) with total signature defect 0.
    Factors whose CM field does not contain K contribute traces, which lie in D_d."""
    factors = factors if factors is not None else simple_factors(d)
    # one unit per factor whose CM field contains K: the one whose twist coset (g N, since H <= N) contains 1
    halves = []
    for f in factors:
        if not f.h <= N:
            continue
        for u in e_weil_units(d, N, [f]):
            if 1 in {u.twist * x % d for x in N}:
                halves.append(u)
                break
    m = [u.defect() for u in halves]
    return [combine(halves, c, d) for c in kernel_basis(m)]


def small_factor_generators(d: int, maxdim: int = 5, factors: Optional[List[Factor]] = None) -> List[Dict[int, int]]:
    """A Z-basis of the Hodge elements supported on the eigencharacters (all representatives) of the simple factors of
    dimension <= maxdim, as residue counts.  Contains (mod D_d and divisor classes) every Hodge class of every abelian
    variety of dimension <= maxdim isogenous to a quotient of a power of J(C_d)."""
    factors = factors if factors is not None else simple_factors(d)
    eig = sorted({v for f in factors if f.simple_dim <= maxdim for v in f.eigencharacters()})
    if not eig:
        return []
    rows = hodge_rows(d, eig)
    out = []
    for c in F.integer_kernel(rows, len(eig)).basis():
        counts: Dict[int, int] = {}
        for cj, v in zip(c, eig):
            if cj:
                for x in v:
                    y = x if cj > 0 else (-x) % d
                    counts[y] = counts.get(y, 0) + abs(cj)
        out.append(counts)
    return out


def counts_to_tuple(counts: Dict[int, int]) -> Tuple_:
    return tuple(sorted(x for x, n in counts.items() for _ in range(n)))


def is_hodge_counts(counts: Dict[int, int], d: int) -> bool:
    L = sum(counts.values())
    if L % 2 or any(x % d == 0 for x in counts):
        return False
    return all(sum(n * ((t * x) % d) for x, n in counts.items()) == L * d // 2 for t in F.half_units(d))


