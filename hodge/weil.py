# Smallest E-Weil realizations of xi_q found by the MILP search of scripts/weil_route.py (docs/fermat/04, Table 3).
# Each entry: (q, N = Gal(Q(mu_q)/E), [(factor beta, twist, multiplicity)]).  The element is the sum of the units.
REALIZATIONS = {
    "44/C5": (44, (1, 5, 9, 25, 37), [((1, 11, 32), 7, 1), ((11, 11, 22), 1, 3)]),
    "44/1": (44, (1,), [((1, 6, 37), 3, 1), ((1, 10, 33), 7, 1), ((1, 12, 31), 21, 1), ((1, 13, 30), 27, 1)]),
    "51/1": (51, (1,), [((1, 4, 46), 14, 1), ((1, 4, 46), 41, 1), ((1, 7, 43), 8, 1), ((1, 17, 33), 46, 1)]),
    "52/1": (52, (1,), [((1, 4, 47), 15, 1), ((1, 6, 45), 1, 1), ((1, 6, 45), 17, 1), ((1, 9, 42), 37, 1)]),
    "52/C3": (52, (1, 9, 29), [((1, 5, 46), 15, 1), ((4, 12, 36), 5, 1)]),
}


def realization(key: str) -> Tuple[Tuple_, int, int]:
    """(element, dimension of the abelian variety of Weil type, degree of the class) for REALIZATIONS[key]."""
    q, Nt, parts = REALIZATIONS[key]
    N = frozenset(Nt)
    fac = {f.beta: f for f in simple_factors(q)}
    elem: List[int] = []
    dim = deg = 0
    for beta, twist, mult in parts:
        f = fac[beta]
        unit = next(u for u in e_weil_units(q, N, [f]) if twist in {u.twist * x % q for x in closure(list(N) + list(f.h), q)})
        elem += list(unit.element()) * mult
        dim += unit.cost * mult
        deg += len(unit.eig) * mult
    return tuple(sorted(elem)), dim, deg


# ------------------------------------------------------------------------------------------- Galois characters

def exponent_counts(counts: Dict[int, int], pd) -> int:
    """galois.exponent_exact for an element given as residue counts (Stickelberger's congruence; the element must be
    Hodge of even length).  Cost is linear in the number of distinct residues, not in the length."""
    l, d = pd.l, pd.d
    L = sum(counts.values())
    if L % 2:
        raise ValueError("odd length")
    den = 1
    for x, n in counts.items():
        den = den * pow(pd.fact[(l - 1) * ((-x) % d) // d], n, l) % l
    val = pow(den, l - 2, l)
    if (L + L // 2) % 2:
        val = (-val) % l
    try:
        return pd.log[val]
    except KeyError:
        raise ValueError("not a Hodge element") from None


def elliptic_divisor_realization(q: int) -> Optional[Tuple[Tuple_, Tuple_]]:
    """Two eigencharacters v1, v2 of CM elliptic-curve factors of J(C_q) (simple factors of dimension 1) such that
    v1 + v2 is a Hodge element of odd parity: a divisor class on E1 x E2 congruent to xi_q mod D_q + S_q."""
    eig = sorted({v for f in simple_factors(q) if f.simple_dim == 1 for v in f.eigencharacters()})
    for i, v1 in enumerate(eig):
        for v2 in eig[i:]:
            el = tuple(sorted(v1 + v2))
            if F.is_hodge_tuple(el, q) and parity(el, q) == 1:
                return v1, v2
    return None
