"""Galois characters of Hodge classes on Fermat varieties, and the field-of-definition obstruction.

See docs/fermat/03-galois-obstruction.md for statements and proofs.

For a Hodge tuple alpha = (a_1, ..., a_L) of degree d (L even), a prime l = 1 (mod 2d) and the prime P of Q(zeta_d)
above l singled out by a primitive root g mod l (zeta_d <-> g^{(l-1)/d} mod P), put

    eps(alpha)(P) = prod_i g(chi^{a_i}) / l^{L/2},    chi(g^k) = exp(2 pi i k / d),   g(chi) = sum_x chi(x) e^{2 pi i x/l}.

By Deligne (Hodge cycles on abelian varieties, Prop. 7.2, Remark 7.3(a), Lemma 7.9, Prop. 7.10) the geometric Frobenius
at P acts on the line of absolute Hodge classes of V(alpha) by eps(alpha)(P)^{-1}; eps(alpha) is a finite-order
character of Gal(Qbar/Q(zeta_d)) with values in mu_{2d}.  It is multiplicative under joins, so it is a homomorphism on
the even-length part of the Hodge lattice B_d.

Values are recorded as exponents k with eps = zeta_{2d}^k, zeta_{2d} <-> g^{(l-1)/(2d)} mod P.  Two independent ways:
  * `exponent_exact`: Stickelberger's congruence, eps = (-1)^{L + L/2} / prod_i b_i!  (mod P), b_i = (l-1)<-a_i/d>;
  * `exponent_float`: Gauss sums in floating point.
"""

from __future__ import annotations

import cmath
from math import gcd
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

from . import formal_module as F


# ------------------------------------------------------------------------------------------- primes

def is_prime(n: int) -> bool:
    if n < 2:
        return False
    i = 2
    while i * i <= n:
        if n % i == 0:
            return False
        i += 1
    return True


def primitive_root(l: int) -> int:
    n, fac, p = l - 1, [], 2
    while p * p <= n:
        if n % p == 0:
            fac.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        fac.append(n)
    return next(g for g in range(2, l) if all(pow(g, (l - 1) // q, l) != 1 for q in fac))


def split_primes(modulus: int, count: int) -> List[int]:
    """The first `count` primes l = 1 (mod modulus)."""
    out, l = [], modulus + 1
    while len(out) < count:
        if is_prime(l):
            out.append(l)
        l += modulus
    return out


class PrimeData:
    """Factorials mod l and the discrete-log table of mu_{2d} for one prime l = 1 (mod 2d)."""

    def __init__(self, l: int, d: int):
        if (l - 1) % (2 * d):
            raise ValueError("need l = 1 mod 2d")
        self.l, self.d = l, d
        self.g = primitive_root(l)
        fact = [1] * l
        for i in range(1, l):
            fact[i] = fact[i - 1] * i % l
        self.fact = fact
        z = pow(self.g, (l - 1) // (2 * d), l)
        self.log: Dict[int, int] = {}
        x = 1
        for k in range(2 * d):
            self.log[x] = k
            x = x * z % l


# ------------------------------------------------------------------------------------------- characters

def exponent_exact(alpha: Sequence[int], pd: PrimeData) -> int:
    """Stickelberger's congruence.  alpha must be a Hodge tuple (not checked here; see CharacterGroup.vector)."""
    l, d = pd.l, pd.d
    L = len(alpha)
    if L % 2:
        raise ValueError("use even-length tuples (join odd ones with d/2)")
    den = 1
    for a in alpha:
        den = den * pd.fact[(l - 1) * ((-a) % d) // d] % l
    val = pow(den, l - 2, l)
    if (L + L // 2) % 2:
        val = (-val) % l
    try:
        return pd.log[val]
    except KeyError:
        # only a partial check: when 2d is close to l - 1, every value lies in mu_2d
        raise ValueError(f"{tuple(alpha)} is not a Hodge tuple of degree {d}") from None


def exponent_float(alpha: Sequence[int], pd: PrimeData) -> Tuple[int, float]:
    """(exponent, distance of the computed angle from the nearest admissible one).  Slow: O(l) per Gauss sum."""
    l, d, g = pd.l, pd.d, pd.g
    ind = [0] * l
    x = 1
    for k in range(l - 1):
        ind[x] = k
        x = x * g % l
    cache: Dict[int, complex] = {}

    def gauss(a: int) -> complex:
        a %= d
        if a not in cache:
            cache[a] = sum(cmath.exp(2j * cmath.pi * (a * ind[x] / d + x / l)) for x in range(1, l)) / l ** 0.5
        return cache[a]

    v = 1 + 0j
    for a in alpha:
        v *= gauss(a)
    ang = cmath.phase(v) / (2 * cmath.pi) * (2 * d)
    k = round(ang)
    return k % (2 * d), max(abs(ang - k), abs(abs(v) - 1))


# ------------------------------------------------------------------------------------------- subgroups

class CharacterGroup:
    """The subgroup of (Z/2d)^N generated by exponent vectors (N = number of primes used)."""

    def __init__(self, d: int, primes: Sequence[int]):
        self.d = d
        self.data = [PrimeData(l, d) for l in primes]
        N, M = len(primes), 2 * d
        self.lattice = F.Lattice(N, [[M if i == j else 0 for j in range(N)] for i in range(N)])
        self._seen = set()

    def vector(self, alpha: Sequence[int]) -> Tuple[int, ...]:
        if not F.is_hodge_tuple(alpha, self.d):
            raise ValueError(f"{tuple(alpha)} is not a Hodge tuple of degree {self.d}")
        return tuple(exponent_exact(alpha, pd) for pd in self.data)

    def add(self, alpha: Sequence[int]) -> None:
        v = self.vector(alpha)
        if v not in self._seen:
            self._seen.add(v)
            self.lattice.add(list(v))

    def contains(self, alpha: Sequence[int]) -> bool:
        return self.lattice.contains(list(self.vector(alpha)))


def known_generators(d: int, max_length: int = 6, enumerate_tuples=None) -> List[Tuple[int, ...]]:
    """Even-length generators of Lambda_d: linear pairs, (d/2, d/2), standard tuples of every degree dividing d (lifted),
    and all Hodge tuples of degree d of length 4..max_length (odd-length Hodge tuples joined with d/2 are among the
    even-length ones, since d/2 is an admissible entry)."""
    enum = enumerate_tuples or F.hodge_tuples
    gens: List[Tuple[int, ...]] = [(a, d - a) for a in range(1, (d + 1) // 2)]
    if d % 2 == 0:
        gens.append((d // 2, d // 2))
    gens += [t for t in F.standard_tuples(d) if len(t) % 2 == 0]
    for L in range(4, max_length + 1, 2):
        gens += list(enum(d, L))
    return gens


def even_form(alpha: Sequence[int], d: int) -> Tuple[int, ...]:
    t = tuple(sorted(a % d for a in alpha))
    if len(t) % 2:
        if d % 2:
            raise ValueError("odd length needs even degree")
        t = tuple(sorted(t + (d // 2,)))
    return t


def galois_obstructed(target: Sequence[int], d: int, nprimes: int = 24, max_length: int = 6,
                      enumerate_tuples=None) -> bool:
    """True if eps(target) is NOT in the group generated by eps(Lambda_d) at the first `nprimes` primes l = 1 mod 2d.
    A True answer is a proof (for these finitely many primes the character differs from every element of the group);
    False only says that these primes do not separate it."""
    grp = CharacterGroup(d, split_primes(2 * d, nprimes))
    for t in known_generators(d, max_length, enumerate_tuples):
        grp.add(t)
    return not grp.contains(even_form(target, d))


# ------------------------------------------------------------------------------------------- sine monomials

def sine_monomial_symbol(exponents: Dict[int, int], d: int, pd: PrimeData) -> int:
    """Legendre symbol, at the prime P of Q(zeta_{2d}) fixed by `pd`, of u = prod_a sin(pi a/d)^{e_a}.
    sin(pi a/d) = (z^a - z^{-a}) / (2i) with z = zeta_{2d} -> g^{(l-1)/(2d)}, i = z^{d/2} (d even)."""
    l = pd.l
    z = pow(pd.g, (l - 1) // (2 * d), l)
    inv2i = pow(2 * pow(z, d // 2, l) % l, l - 2, l)
    u = 1
    for a, e in exponents.items():
        s = (pow(z, a, l) - pow(z, 2 * d - a, l)) * inv2i % l
        u = u * pow(s, e % (l - 1), l) % l
    return 1 if pow(u, (l - 1) // 2, l) == 1 else -1


def discrete_log(pd: PrimeData, b: int) -> int:
    x, k = 1, 0
    while x != b % pd.l:
        x, k = x * pd.g % pd.l, k + 1
    return k


