"""Which Fermat degrees d have the Hodge conjecture for all dimensions, by the cited theorems?

MMRV (arXiv:2609.27301) Corollary 4.1: if T_d, the G_d-module generated by Aoki's exceptional elements xi_q for the
q in Q dividing d, lies in the algebraic classes, then HC holds for every (weighted) Fermat variety of degree d.  By
Aoki's generation theorem (MMRV Thm 4.2) these xi_q generate B_d/(D_d + S_d).  Lifting preserves algebraicity
(MMRV Prop. 3.2), and the algebraic classes form a G_d-submodule.  MMRV Theorem 1.1 settles every degree d < 65 with
d != 44, 51, 52, so every q in Q with q < 65 and q not in {44, 51, 52} has xi_q algebraic.  Hence HC holds in degree d
as soon as every q in Q dividing d is one of those ("settled").  See docs/02-known-cases.md, section 2.4.

Q is the set of products of an even number of distinct elements of P = {4} u {odd primes} (MMRV Def. 4.8).
"""

from __future__ import annotations

from itertools import combinations
from typing import List

# q in Q with q < 65, other than 44, 51, 52: xi_q is algebraic by MMRV Theorem 1.1.
SETTLED = frozenset({12, 15, 20, 21, 28, 33, 35, 39, 55, 57})
OPEN_BELOW_65 = frozenset({44, 51, 52})


def _is_prime(n: int) -> bool:
    return n >= 2 and all(n % k for k in range(2, int(n ** 0.5) + 1))


def p_factors(d: int) -> List[int]:
    """The elements of P dividing d: 4 if 4 | d, and the odd primes dividing d."""
    out = [4] if d % 4 == 0 else []
    out += [p for p in range(3, d + 1, 2) if d % p == 0 and _is_prime(p)]
    return out


def q_divisors(d: int) -> List[int]:
    """All q in Q dividing d (products of an even number >= 2 of distinct P-factors of d)."""
    P = p_factors(d)
    out = []
    for r in range(2, len(P) + 1, 2):
        for c in combinations(P, r):
            prod = 1
            for x in c:
                prod *= x
            out.append(prod)
    return sorted(out)


def covered(d: int) -> bool:
    """True if HC for all Fermat varieties of degree d follows from MMRV Thm 1.1, Cor. 4.1, Prop. 3.2 and Aoki."""
    return all(q in SETTLED for q in q_divisors(d))


def uncovered(n: int) -> List[int]:
    return [d for d in range(3, n + 1) if not covered(d)]


def minimal_open_q(n: int) -> List[int]:
    """The q in Q, q <= n, that are not settled (each one blocks all its multiples)."""
    return sorted(q for d in range(3, n + 1) for q in [d] if q in q_divisors(q) and q not in SETTLED)
