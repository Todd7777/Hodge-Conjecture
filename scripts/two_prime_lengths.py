#!/usr/bin/env python3
"""Regenerate results/two_prime_lengths.md: Theorem T of docs/fermat/02-exceptional-lengths.md section 6.

For every q = p1 p2 (5 <= p1 < p2 primes) up to MAX (default 415, the range of MMRV's Table 1):
  * the formula phi(q)/4 + c_{p1}(p2) + c_{p2}(p1);
  * the exact lower-bound checks (Proposition T1: the coset functionals are even on every standard tuple; Propositions
    T2 and T3: the explicit element xi'_q is a Hodge tuple, odd on every functional);
  * the upper bound (Proposition T4): the tuple built from adapted half systems has exactly that length;
  * for comparison, the MILP representatives (hodge/two_prime.py REPRESENTATIVES, q <= 300) and MMRV's Table 1.

    python3 scripts/two_prime_lengths.py [MAX] [--search] [OUTPUT]

--search re-finds the representatives with a MILP (needs scipy) for every q <= MAX and prints them.
Without it the script is pure Python and takes about a minute.
"""
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from hodge import formal_module as F  # noqa: E402
from hodge import two_prime as T  # noqa: E402

# MMRV Table 1 (upper bounds for l_{2,q}(xi_q) from the Aoki-Shioda algorithm), the entries with q = p1 p2, p1 >= 5.
MMRV = {35: 8, 55: 10, 65: 16, 77: 16, 85: 18, 91: 22, 95: 20, 115: 24, 119: 26, 133: 28, 143: 32, 145: 32, 155: 30,
        161: 34, 185: 38, 187: 42, 203: 42, 205: 42, 209: 46, 215: 44, 217: 46, 221: 54, 235: 48, 247: 56, 253: 56,
        259: 54, 265: 54, 287: 64, 295: 60, 299: 68, 301: 70, 305: 62, 319: 72, 323: 74, 329: 70, 335: 70, 341: 76,
        355: 70, 365: 74, 371: 80, 377: 86, 391: 90, 395: 80, 403: 94, 407: 96, 413: 88, 415: 84}


def milp_representative(q):
    import numpy as np
    from scipy.optimize import Bounds, LinearConstraint, milp
    from hodge import weil as W
    phi = W.parity_functional(q)
    res_ = list(range(1, q))
    par = [bin(W._mask(F.fold((a,), q)) & phi).count("1") % 2 for a in res_]
    rows = [[2 * ((s * a) % q) - q for a in res_] + [0] for s in F.half_units(q) + [1]]
    cons = [LinearConstraint(np.array(rows, dtype=float), 0, 0),
            LinearConstraint(np.array([par + [-2]], dtype=float), 1, 1)]
    res = milp(np.array([1] * len(res_) + [0], dtype=float), constraints=cons, integrality=np.ones(len(res_) + 1),
               bounds=Bounds(0, 40), options={"time_limit": 900, "mip_rel_gap": 0})
    x = [int(round(v)) for v in res.x[:-1]]
    return tuple(a for a, k in zip(res_, x) for _ in range(k))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    qmax = int(args[0]) if args else 415
    out = args[1] if len(args) > 1 else os.path.join(ROOT, "results", "two_prime_lengths.md")
    qs = sorted(p1 * p2 for p1 in range(5, qmax) for p2 in range(p1 + 1, qmax)
                if T.is_prime(p1) and T.is_prime(p2) and p1 * p2 <= qmax)
    lines = ["# Exceptional lengths for q = p1 p2", "",
             f"Generated by `python3 scripts/two_prime_lengths.py {qmax}`. Statement and proof: "
             "`docs/fermat/02-exceptional-lengths.md` §6 (Theorem T). Code: `hodge/two_prime.py`.", "",
             "*formula* = φ(q)/4 + c_{p1}(p2) + c_{p2}(p1), with c_r(p) = (p−1)/ord_p(r) if ord_p(r) is even, else 0. "
             "*T1* = every coset functional is even on every standard tuple (checked exactly; proved in general). "
             "*T2–T3* = the explicit element ξ′_q is a Hodge tuple and is odd on every functional (checked exactly; "
             "proved in general). Together they give l_{2,q}(ξ_q) ≥ formula. *T4* = the tuple built from adapted half "
             "systems (`two_prime.shortest_tuple`) is Hodge, has one entry in every coset support and has the formula "
             "length, which gives equality (proved in general). *MILP* = length of the representative found earlier "
             "by a MILP (q ≤ 300, verified exactly). *MMRV* = their Table 1 upper bound (Cited).", "",
             "| q | p1 | p2 | φ(q)/4 | c_{p1}(p2) | c_{p2}(p1) | formula | T1 | T2–T3 | T4 | MILP | MMRV | f_0(q) |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    t0 = time.time()
    for q in qs:
        p1, p2 = T.factor(q)
        bound = T.predicted_length(q)
        funcs = T.coset_functionals(q)
        std = F.standard_tuples(q)
        f1 = all(T.count(s, t, q) % 2 == 0 for _, s in funcs for t in std)
        xi = T.aoki_xi(q)
        f23 = F.is_hodge_tuple(xi, q) and all(T.count(s, xi, q) % 2 == 1 for _, s in funcs)
        st = T.shortest_tuple(q)
        f4 = F.is_hodge_tuple(st, q) and len(st) == bound and all(T.count(s, st, q) == 1 for _, s in funcs)
        rep = T.REPRESENTATIVES.get(q)
        if "--search" in sys.argv:
            rep = milp_representative(q)
            print(f"    {q}: {rep},", flush=True)
        ours = ""
        if rep is not None:
            v = T.verify(q, rep)
            assert v["rep_hodge"] and v["rep_outside"] and v["odd_on_rep"] and v["kills_S"]
            ours = str(len(rep))
        mm = MMRV.get(q)
        exact = str(bound) if (f1 and f23 and f4) else "?"
        lines.append(f"| {q} | {p1} | {p2} | {(p1 - 1) * (p2 - 1) // 4} | {T.c_term(p1, p2)} | {T.c_term(p2, p1)} | "
                     f"{bound} | {'yes' if f1 else 'NO'} | {'yes' if f23 else 'NO'} | {'yes' if f4 else 'NO'} | {ours} | "
                     f"{mm if mm else ''} | {exact} |")
    lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out} ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
