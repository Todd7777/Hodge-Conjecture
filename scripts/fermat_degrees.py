#!/usr/bin/env python3
"""Regenerate results/fermat_degrees.md: the Fermat degrees d <= N for which the Hodge conjecture (all dimensions)
follows from MMRV Theorem 1.1, Corollary 4.1, Proposition 3.2 and Aoki's generation theorem (hodge/fermat_degrees.py).

    python3 scripts/fermat_degrees.py [N] [OUTPUT]      (defaults: 1000, results/fermat_degrees.md)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from hodge import fermat_degrees as FD  # noqa: E402


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "results", "fermat_degrees.md")
    unc = FD.uncovered(n)
    mins = FD.minimal_open_q(n)
    lines = ["# Fermat degrees settled by the cited theorems", "",
             f"Generated by `python3 scripts/fermat_degrees.py {n}`. Rule (`hodge/fermat_degrees.py`): HC holds for every "
             "Fermat variety of degree d, in every dimension, when every q ∈ Q dividing d is one of the settled "
             f"{sorted(FD.SETTLED)} (MMRV Theorem 1.1, Corollary 4.1, Proposition 3.2; Aoki's generation theorem). "
             "This is a corollary of published results, not a new case.", "",
             f"* Degrees 3 ≤ d ≤ {n}: {n - 2 - len(unc)} covered, {len(unc)} not covered.",
             f"* Covered between 65 and 100: {[d for d in range(65, 101) if FD.covered(d)]}.",
             f"* Not covered up to 200: {[d for d in unc if d <= 200]}.",
             "", f"Elements q ∈ Q, q ≤ {n}, that are not settled (each blocks all its multiples; "
             "`minimal_open_q`):", "", ", ".join(map(str, mins)), ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out, len(unc), "uncovered of", n - 2)


if __name__ == "__main__":
    main()
