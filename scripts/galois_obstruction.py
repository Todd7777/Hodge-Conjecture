#!/usr/bin/env python3
"""Regenerate results/galois_obstruction.md: the Galois field-of-definition test of docs/fermat/03-galois-obstruction.md
for Aoki's exceptional tuples xi_q in their own degree and in multiples.

For each (q, D): is the Galois character of lift_D(xi_q) in the group generated by the characters of Lambda_D
(linear pairs, (D/2, D/2), standard tuples of all degrees dividing D, all Hodge tuples of degree D of length 4 and 6)?
Characters are compared at the first 24 primes l = 1 (mod 2D), with exact (Stickelberger) values.

Needs numpy and a C compiler (for scripts/fermat_hodge_tuples.c).  Usage:
    python3 scripts/galois_obstruction.py [MAX_DEGREE] [OUTPUT]       (defaults: 572, results/galois_obstruction.md)
The full run takes about 25 minutes on one core (degrees 528 and 572 alone take about 15).
"""
import os
import subprocess
import sys
import tempfile
import time

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from hodge import formal_module as F  # noqa: E402
from hodge import galois as G  # noqa: E402

# Aoki's exceptional tuples as used in docs/fermat/01-span-test.md (MMRV's authors' list), q < 70.
XI = {12: (1, 4, 9, 10), 15: (1, 7, 10, 12), 20: (1, 6, 8, 17, 18), 21: (1, 10, 15, 16),
      28: (1, 8, 9, 10, 12, 17, 21, 22, 26), 33: (1, 4, 13, 16, 19, 22, 27, 30), 35: (1, 2, 16, 17, 21, 22, 30, 31),
      39: (1, 4, 15, 16, 19, 21, 27, 28, 30, 34), 44: (1, 5, 6, 13, 14, 18, 20, 33, 34, 37, 41, 42),
      51: (1, 10, 13, 18, 22, 28, 34, 37, 43, 49), 52: (1, 10, 14, 17, 18, 21, 22, 24, 29, 41, 45, 46, 50),
      55: (1, 2, 12, 15, 16, 26, 27, 30, 35, 37, 41, 45, 46, 52),
      57: (1, 4, 7, 9, 13, 16, 28, 33, 40, 45, 46, 51, 52, 54),
      65: (1, 2, 6, 16, 17, 21, 27, 32, 41, 42, 45, 47, 52, 55, 56, 60),
      68: (1, 4, 5, 9, 12, 13, 14, 37, 38, 42, 45, 46, 49, 50, 58, 61, 62, 66),
      69: (1, 4, 9, 10, 16, 25, 28, 31, 34, 39, 40, 43, 46, 54, 55, 57, 63, 66)}
STATUS = {12: "algebraic", 15: "algebraic", 20: "algebraic", 21: "algebraic", 28: "algebraic", 33: "algebraic",
          35: "algebraic (via degree 70)", 39: "algebraic", 55: "algebraic (via degree 110)",
          57: "algebraic (via degree 114)", 44: "open", 51: "open", 52: "open", 65: "open (q > 64)",
          68: "open (q > 64)", 69: "open (q > 64)"}
PLAN = {12: [12], 15: [15], 20: [20], 21: [21], 28: [28], 33: [33, 66], 35: [35, 70, 105, 140], 39: [39, 78],
        55: [55, 110], 57: [57, 114], 44: [44 * k for k in range(1, 14)], 51: [51, 102, 153, 204],
        52: [52, 104, 156, 208, 260], 65: [65, 130, 195], 68: [68, 136, 204], 69: [69, 138, 207]}


def build_enumerator(tmp):
    exe = os.path.join(tmp, "fermat_hodge_tuples")
    subprocess.run(["gcc", "-O2", "-o", exe, os.path.join(ROOT, "scripts", "fermat_hodge_tuples.c")], check=True)
    return exe


def enum(exe, D, L):
    out = subprocess.run([exe, str(D), str(L)], capture_output=True, text=True, check=True).stdout
    rows = [list(map(int, s.split())) for s in out.splitlines() if s.strip()]
    return np.array(rows, dtype=np.int64).reshape(-1, L)


def exps(T, pd):
    """Vectorised exponent_exact for the rows of T (equal even length)."""
    l, D = pd.l, pd.d
    fact = np.array(pd.fact, dtype=np.int64)
    b = ((l - 1) // D) * ((-T) % D)
    den = np.ones(T.shape[0], dtype=np.int64)
    for j in range(T.shape[1]):
        den = den * fact[b[:, j]] % l
    inv, base, e = np.ones_like(den), den.copy(), l - 2
    while e:
        if e & 1:
            inv = inv * base % l
        base, e = base * base % l, e >> 1
    if (T.shape[1] + T.shape[1] // 2) % 2:
        inv = (-inv) % l
    logt = -np.ones(l, dtype=np.int64)
    for v, k in pd.log.items():
        logt[v] = k
    k = logt[inv]
    if (k < 0).any():
        raise ValueError("a generator is not a Hodge tuple")
    return k


def lambda_group(D, exe, nprimes=24):
    """(prime data, lattice of exponent vectors of eps(Lambda_D) plus 2D Z^N, number of generators, distinct vectors)."""
    data = [G.PrimeData(l, D) for l in G.split_primes(2 * D, nprimes)]
    blocks = [np.array([(a, D - a) for a in range(1, (D + 1) // 2)] + ([(D // 2, D // 2)] if D % 2 == 0 else []),
                       dtype=np.int64)]
    by_len = {}
    for t in F.standard_tuples(D):
        by_len.setdefault(len(t), []).append(t)
    blocks += [np.array(v, dtype=np.int64) for v in by_len.values()]
    blocks += [enum(exe, D, 4), enum(exe, D, 6)]
    vecs = [np.stack([exps(B, pd) for pd in data], axis=1) for B in blocks if B.shape[0]]
    V = np.unique(np.concatenate(vecs), axis=0)
    N, M = len(data), 2 * D
    lat = F.Lattice(N, [[M if i == j else 0 for j in range(N)] for i in range(N)])
    for v in V:
        lat.add([int(x) for x in v])
    return data, lat, sum(B.shape[0] for B in blocks), len(V)


def test(q, D, exe, nprimes=24):
    t0 = time.time()
    data, lat, ngens, ndistinct = lambda_group(D, exe, nprimes)
    target = G.even_form(F.lift(XI[q], q, D), D)
    assert F.is_hodge_tuple(target, D)
    tv = [G.exponent_exact(target, pd) for pd in data]
    member = lat.contains(tv)
    return member, ngens, ndistinct, time.time() - t0


def main():
    dmax = int(sys.argv[1]) if len(sys.argv) > 1 else 572
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "results", "galois_obstruction.md")
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        exe = build_enumerator(tmp)
        for q, Ds in PLAN.items():
            for D in Ds:
                if D > dmax:
                    continue
                member, ng, nd, dt = test(q, D, exe)
                print(f"q={q} D={D}: reached={member} ({ng} generators, {nd} distinct characters, {dt:.0f}s)", flush=True)
                rows.append(f"| {q} | {STATUS[q]} | {D} | {'**no**' if not member else 'yes'} | {ng} | {nd} | {dt:.0f} |")
    with open(out, "w") as f:
        f.write("# Galois field-of-definition test for the exceptional tuples\n\n")
        f.write(f"Generated by `python3 scripts/galois_obstruction.py {dmax}`. Statement and proof: "
                "`docs/fermat/03-galois-obstruction.md`. Characters compared exactly at the first 24 primes "
                "l ≡ 1 (mod 2D).\n\n")
        f.write("Column *reached*: is the Galois character of the lift of ξ_q to degree D in the group generated by "
                "the characters of Λ_D (linear pairs, standard tuples of every degree dividing D, all Hodge tuples of "
                "degree D of length ≤ 6)? **no** means: no algebraic cycle defined over the field F_D cut out by those "
                "characters has a nonzero component on the eigenline of ξ_q (Theorem G). *yes* means only that "
                "these primes do not separate the characters.\n\n")
        f.write("| q | status of ξ_q | D | reached | generators | distinct characters | seconds |\n")
        f.write("|---|---|---|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
