#!/usr/bin/env python3
"""Regenerate results/lift_lengths.md: docs/fermat/05-lifts.md, sections 3 and 4.

Part 1: for odd two-factor q, f_0(q) (Theorem T), the doubling bound g(q) (Theorem L2) and the exact MILP value of
l_{2,2q}(xi_q).  Part 2 (--multipliers): for every two-factor q in Q with QMIN <= q < QMAX and every k <= 8 with
kq <= DMAX, the MILP minimum length of a Hodge tuple of degree kq in the class lift(xi_q) + (settled classes) +
D + S, with no component on other open classes.  Every representative found is checked exactly: it is a Hodge tuple,
and lattice membership confirms its class.

Needs scipy (HiGHS).  Usage:
    python3 scripts/lift_lengths.py [--multipliers] [QMAX] [DMAX] [OUTPUT]   (defaults 100, 560, results/lift_lengths.md)
Part 1 takes about a minute; part 2 about an hour on one core (some odd-k cases stop at the 300 s time limit).
"""
import itertools
import os
import sys
import time

import numpy as np
from scipy.optimize import Bounds, LinearConstraint, milp

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from hodge import exceptional_length as EL  # noqa: E402
from hodge import fermat_degrees as FD  # noqa: E402
from hodge import formal_module as F  # noqa: E402
from hodge import lifts as LF  # noqa: E402
from hodge import two_prime as T  # noqa: E402
from hodge import weil as W  # noqa: E402

MMRV3 = {33: 4, 35: 6, 39: 3, 51: 7, 55: 5, 57: 6, 65: 10, 69: 9, 77: 12, 85: 12, 87: 10, 91: 17, 93: 10, 95: 10, 111: 10}


def xi_rep(q):
    """A tuple in the class of xi_q (two P-factors): Theorem D/D' tuples for 4p and 3p, Theorem T tuples otherwise."""
    try:
        EL.family(q, both=True)
        return EL.minimal_tuple(q)
    except ValueError:
        return T.shortest_tuple(q)


def search(q, D, tl=300):
    if len(FD.p_factors(D)) >= 4:          # an element of Q with four P-factors divides D: its xi is not used here
        return None
    divs = FD.q_divisors(D)
    lifts = {x: F.lift(xi_rep(x), x, D) for x in divs}
    std = F.standard_tuples(D)
    rows = [W._mask(F.fold(s, D)) for s in std]
    phis = {}
    for x in divs:
        others = [W._mask(F.fold(lifts[o], D)) for o in divs if o != x]
        phis[x] = W._gf2_solve(rows + others, W._mask(F.fold(lifts[x], D)))
        assert phis[x] is not None
    res_ = list(range(1, D))
    constrained = [q] + [o for o in divs if o != q and o not in FD.SETTLED]
    nz = len(constrained)
    A, lo, hi = [], [], []
    for s in F.half_units(D) + [1]:
        A.append([2 * ((s * a) % D) - D for a in res_] + [0] * nz)
        lo.append(0)
        hi.append(0)
    for j, o in enumerate(constrained):
        pv = [bin(W._mask(F.fold((a,), D)) & phis[o]).count("1") % 2 for a in res_]
        z = [0] * nz
        z[j] = -2
        A.append(pv + z)
        v = 1 if o == q else 0
        lo.append(v)
        hi.append(v)
    res = milp(np.array([1] * len(res_) + [0] * nz, dtype=float), constraints=[LinearConstraint(np.array(A, float), lo, hi)],
               integrality=np.ones(len(res_) + nz), bounds=Bounds(0, 30),
               options={"time_limit": tl, "mip_rel_gap": 0})
    x = [int(round(v)) for v in res.x[:len(res_)]]
    tup = tuple(a for a, k in zip(res_, x) for _ in range(k))
    assert F.is_hodge_tuple(tup, D)
    S = F.span_folded(std, D)
    settled = [o for o in divs if o != q and o in FD.SETTLED]
    ok = False
    for cs in itertools.product((0, 1), repeat=len(settled)):
        v = [a - b for a, b in zip(F.fold(tup, D), F.fold(lifts[q], D))]
        for c, o in zip(cs, settled):
            if c:
                v = [a - b for a, b in zip(v, F.fold(lifts[o], D))]
        if S.contains(v):
            ok = True
            break
    assert ok, (q, D)
    dual = getattr(res, "mip_dual_bound", None)
    return tup, int(res.status), dual, divs


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    qmax = int(args[0]) if args else 100
    dmax = int(args[1]) if len(args) > 1 else 560
    out = args[2] if len(args) > 2 else os.path.join(ROOT, "results", "lift_lengths.md")
    lines = ["# Lifted lengths of the exceptional classes", "",
             f"Generated by `python3 scripts/lift_lengths.py{' --multipliers' if '--multipliers' in sys.argv else ''}"
             f" {qmax} {dmax}`. Statements: `docs/fermat/05-lifts.md`. MILP = HiGHS via scipy; status 0 = proved optimal "
             "by the solver, 1 = time limit (the length is then an upper bound and the dual bound a lower bound). Every "
             "representative is verified exactly (Hodge, and its class by lattice membership).", "",
             "## 1. Doubling: l_{2,2q}(ξ_q) for odd two-factor q", "",
             "| q | f_0(q) | g(q) | MILP l_{2,2q} | status | MMRV Table 3 | representative |", "|---|---|---|---|---|---|---|"]
    qs = sorted(p1 * p2 for p1 in range(3, 60) for p2 in range(p1 + 1, 60)
                if T.is_prime(p1) and T.is_prime(p2) and p1 * p2 <= 160)
    for q in qs:
        tup, st, dual, _ = search(q, 2 * q)
        g = LF.doubling_bound(q)
        assert len(tup) >= g
        lines.append(f"| {q} | {T.predicted_length(q)} | {g} | {len(tup)} | {st} | {MMRV3.get(q, '—')} | {tup} |")
        print("doubling", q, len(tup), flush=True)
    lines.append("")
    if "--multipliers" in sys.argv:
        lines += ["## 2. Multipliers k ≤ 8 for the two-factor q ∈ Q with 65 ≤ q < " + str(qmax), "",
                  "| q | D = kq | k | Q-divisors of D | min length | status | dual bound | seconds |",
                  "|---|---|---|---|---|---|---|---|"]
        targets = [q for q in range(65, qmax) if q in FD.q_divisors(q) and len(FD.p_factors(q)) == 2]
        for q in targets:
            for k in range(2, 9):
                D = k * q
                if D > dmax:
                    continue
                if len(FD.p_factors(D)) >= 4:
                    lines.append(f"| {q} | {D} | {k} | (four P-factors: skipped) | | | | |")
                    continue
                t0 = time.time()
                tup, st, dual, divs = search(q, D)
                dt = time.time() - t0
                lines.append(f"| {q} | {D} | {k} | {divs} | {len(tup)} | {st} | "
                             f"{'' if dual is None else round(dual, 2)} | {dt:.0f} |")
                print("multiplier", q, D, len(tup), st, flush=True)
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
